import { Prisma } from "@prisma/client";

import { POST_FORM_LABELS } from "@/data/dashboard/ui";
import type { FaqInput, PostFieldErrors, PostInput, PostMutationResult } from "@/types/api";
import { prisma } from "@/server/config/prisma";
import { sanitizePostHtml } from "@/server/services/sanitizer";
import { resolveSlug } from "@/lib/slug";
import { hasSeoData, normalizeOptionalText, normalizeSeoInput, type NormalizedSeo } from "@/server/services/normalization";
import { resolveUniqueSlug } from "@/server/services/slug.service";
import { normalizePostFaqs } from "@/server/services/faqs.service";

interface NormalizedPost {
  title: string;
  slug: string;
  excerpt: string | null;
  categoryIds: number[];
  tagIds: number[];
  readTimeMinutes: number | null;
  content: string | null;
  coverImage: string | null;
  coverImageAlt: string | null;
  seo: NormalizedSeo;
  status: "DRAFT" | "PUBLISHED";
  faqs?: FaqInput[];
}

type PostNormalizationResult =
  | { ok: true; data: NormalizedPost; slugAutoGenerated: boolean }
  | { ok: false; fieldErrors: PostFieldErrors };

function isSlugConflict(error: unknown): boolean {
  return error instanceof Prisma.PrismaClientKnownRequestError && error.code === "P2002";
}

function normalizePostInput(input: PostInput): PostNormalizationResult {
  const errors: PostFieldErrors = {};

  const title = String(input.title ?? "").trim();
  if (!title) errors.title = POST_FORM_LABELS.titleRequired;

  const slugResolution = resolveSlug(String(input.slug ?? ""), title);
  if (!slugResolution.ok) {
    errors.slug =
      slugResolution.reason === "empty" ? POST_FORM_LABELS.slugRequired : POST_FORM_LABELS.slugInvalid;
  }

  const categoryIds = Array.isArray(input.categoryIds)
    ? Array.from(
        new Set(
          input.categoryIds
            .map((id) => Number(id))
            .filter((id) => Number.isInteger(id) && id > 0),
        ),
      )
    : [];

  const tagIds = Array.isArray(input.tagIds)
    ? input.tagIds.map((id) => Number(id)).filter((id) => Number.isInteger(id) && id > 0)
    : [];

  const readTimeRaw = String(input.readTimeMinutes ?? "").trim();
  let readTimeMinutes: number | null = null;
  if (readTimeRaw !== "") {
    const parsed = Number(readTimeRaw);
    if (Number.isInteger(parsed) && parsed > 0) {
      readTimeMinutes = parsed;
    } else {
      errors.readTimeMinutes = POST_FORM_LABELS.readTimeInvalid;
    }
  }

  if (Object.keys(errors).length > 0) return { ok: false, fieldErrors: errors };

  const excerpt = String(input.excerpt ?? "").trim();
  const rawContent = String(input.content ?? "").trim();

  return {
    ok: true,
    slugAutoGenerated: slugResolution.ok && slugResolution.autoGenerated,
    data: {
      title,
      slug: slugResolution.ok ? slugResolution.slug : "",
      excerpt: excerpt.length > 0 ? excerpt : null,
      categoryIds,
      tagIds,
      readTimeMinutes,
      content: rawContent.length > 0 ? sanitizePostHtml(rawContent) : null,
      coverImage: normalizeOptionalText(input.coverImage),
      coverImageAlt: normalizeOptionalText(input.coverImageAlt),
      seo: normalizeSeoInput(input),
      status: input.status === "DRAFT" ? "DRAFT" : "PUBLISHED",
      faqs: input.faqs === undefined ? undefined : normalizePostFaqs(input.faqs),
    },
  };
}

export async function createPost(input: PostInput): Promise<PostMutationResult> {
  const result = normalizePostInput(input);
  if (!result.ok) return { ok: false, fieldErrors: result.fieldErrors };

  const { data, slugAutoGenerated } = result;
  const slug = await resolveUniqueSlug("post", data.slug, slugAutoGenerated, null);
  if (slug === null) return { ok: false, fieldErrors: { slug: POST_FORM_LABELS.slugTaken } };

  const publishDate = data.status === "PUBLISHED" ? new Date() : null;
  try {
    const { tagIds, categoryIds, content, seo, faqs, ...postData } = data;
    const post = await prisma.post.create({
      data: {
        ...postData,
        slug,
        content: content ?? Prisma.DbNull,
        date: publishDate,
        categories: { connect: categoryIds.map((id) => ({ id })) },
        tags: { connect: tagIds.map((id) => ({ id })) },
        faqs:
          faqs && faqs.length > 0
            ? {
                create: faqs.map((faq, index) => ({
                  ...faq,
                  location: "BLOG",
                  order: index,
                  isActive: true,
                })),
              }
            : undefined,
      },
    });
    if (hasSeoData(seo)) {
      await prisma.seoMetadata.create({ data: { postId: post.id, ...seo } });
    }
  } catch (error) {
    if (isSlugConflict(error)) {
      return { ok: false, fieldErrors: { slug: POST_FORM_LABELS.slugTaken } };
    }
    console.error("createPost failed:", error);
    return { ok: false, message: POST_FORM_LABELS.error };
  }

  return { ok: true, slug };
}

export async function updatePost(input: PostInput & { currentSlug: string }): Promise<PostMutationResult> {
  const { currentSlug, ...rawInput } = input;
  const result = normalizePostInput(rawInput);
  if (!result.ok) return { ok: false, fieldErrors: result.fieldErrors };
  const { data, slugAutoGenerated } = result;

  const current = await prisma.post.findUnique({
    where: { slug: currentSlug },
    select: { id: true, deletedAt: true, status: true, date: true },
  });
  if (!current || current.deletedAt) return { ok: false, message: POST_FORM_LABELS.error };

  const slug = await resolveUniqueSlug("post", data.slug, slugAutoGenerated, current.id);
  if (slug === null) return { ok: false, fieldErrors: { slug: POST_FORM_LABELS.slugTaken } };

  const firstPublication = data.status === "PUBLISHED" && !current.date;
  const publishDate = firstPublication ? new Date() : current.date;

  try {
    const { tagIds, categoryIds, content, seo, faqs, ...postData } = data;
    await prisma.$transaction([
      prisma.post.update({
        where: { slug: currentSlug },
        data: {
          ...postData,
          slug,
          content: content === null ? Prisma.DbNull : content,
          date: publishDate,
          categories: { set: categoryIds.map((id) => ({ id })) },
          tags: { set: tagIds.map((id) => ({ id })) },
        },
      }),
      seoWriteOps(current.id, seo),
      ...(faqs
        ? [
            prisma.faq.deleteMany({ where: { postId: current.id } }),
            ...(faqs.length > 0
              ? [
                  prisma.faq.createMany({
                    data: faqs.map((faq, index) => ({
                      ...faq,
                      location: "BLOG" as const,
                      postId: current.id,
                      order: index,
                      isActive: true,
                    })),
                  }),
                ]
              : []),
          ]
        : []),
    ]);
  } catch (error) {
    if (isSlugConflict(error)) {
      return { ok: false, fieldErrors: { slug: POST_FORM_LABELS.slugTaken } };
    }
    console.error("updatePost failed:", error);
    return { ok: false, message: POST_FORM_LABELS.error };
  }

  return { ok: true, slug };
}

function seoWriteOps(postId: number, seo: NormalizedSeo) {
  return hasSeoData(seo)
    ? prisma.seoMetadata.upsert({
        where: { postId },
        create: { postId, ...seo },
        update: { ...seo },
      })
    : prisma.seoMetadata.deleteMany({ where: { postId } });
}

export async function trashPost(slug: string): Promise<{ ok: boolean }> {
  try {
    const result = await prisma.post.updateMany({
      where: { slug, deletedAt: null },
      data: { deletedAt: new Date() },
    });
    if (result.count === 0) return { ok: false };
  } catch {
    return { ok: false };
  }

  return { ok: true };
}

export async function restorePost(slug: string): Promise<{ ok: boolean }> {
  try {
    const result = await prisma.post.updateMany({
      where: { slug, deletedAt: { not: null } },
      data: { deletedAt: null },
    });
    if (result.count === 0) return { ok: false };
  } catch {
    return { ok: false };
  }

  return { ok: true };
}

export async function deletePostPermanently(slug: string): Promise<{ ok: boolean }> {
  try {
    await prisma.post.delete({ where: { slug } });
  } catch {
    return { ok: false };
  }

  return { ok: true };
}
