import { Prisma } from "@prisma/client";

import { PAGES_FORM_LABELS } from "@/data/dashboard/ui";
import type { PageFieldErrors, PageInput, PageMutationResult } from "@/types/api";
import { prisma } from "@/server/config/prisma";
import { sanitizePostHtml } from "@/server/services/sanitizer";
import { resolveSlug } from "@/lib/slug";
import { hasSeoData, normalizeOptionalText, normalizeSeoInput, type NormalizedSeo } from "@/server/services/normalization";
import { resolveUniqueSlug } from "@/server/services/slug.service";

interface NormalizedPage {
  title: string;
  slug: string;
  content: string | null;
  coverImage: string | null;
  coverImageAlt: string | null;
  seo: NormalizedSeo;
  status: "DRAFT" | "PUBLISHED";
}

type PageNormalizationResult =
  | { ok: true; data: NormalizedPage; slugAutoGenerated: boolean }
  | { ok: false; fieldErrors: PageFieldErrors };

function isSlugConflict(error: unknown): boolean {
  return error instanceof Prisma.PrismaClientKnownRequestError && error.code === "P2002";
}

function normalizePageInput(input: PageInput): PageNormalizationResult {
  const errors: PageFieldErrors = {};

  const title = String(input.title ?? "").trim();
  if (!title) errors.title = PAGES_FORM_LABELS.titleRequired;

  const slugResolution = resolveSlug(String(input.slug ?? ""), title);
  if (!slugResolution.ok) {
    errors.slug =
      slugResolution.reason === "empty" ? PAGES_FORM_LABELS.slugRequired : PAGES_FORM_LABELS.slugInvalid;
  }

  if (Object.keys(errors).length > 0) return { ok: false, fieldErrors: errors };

  const rawContent = String(input.content ?? "").trim();

  return {
    ok: true,
    slugAutoGenerated: slugResolution.ok && slugResolution.autoGenerated,
    data: {
      title,
      slug: slugResolution.ok ? slugResolution.slug : "",
      content: rawContent.length > 0 ? sanitizePostHtml(rawContent) : null,
      coverImage: normalizeOptionalText(input.coverImage),
      coverImageAlt: normalizeOptionalText(input.coverImageAlt),
      seo: normalizeSeoInput(input),
      status: input.status === "DRAFT" ? "DRAFT" : "PUBLISHED",
    },
  };
}

function seoWriteOps(pageId: number, seo: NormalizedSeo) {
  return hasSeoData(seo)
    ? prisma.seoMetadata.upsert({
        where: { pageId },
        create: { pageId, ...seo },
        update: { ...seo },
      })
    : prisma.seoMetadata.deleteMany({ where: { pageId } });
}

export async function createPage(input: PageInput): Promise<PageMutationResult> {
  const result = normalizePageInput(input);
  if (!result.ok) return { ok: false, fieldErrors: result.fieldErrors };

  const { data, slugAutoGenerated } = result;
  const slug = await resolveUniqueSlug("page", data.slug, slugAutoGenerated, null);
  if (slug === null) return { ok: false, fieldErrors: { slug: PAGES_FORM_LABELS.slugTaken } };

  const publishedAt = data.status === "PUBLISHED" ? new Date() : null;
  try {
    const { seo, ...pageData } = data;
    const page = await prisma.page.create({
      data: {
        ...pageData,
        slug,
        content: pageData.content ?? Prisma.DbNull,
        publishedAt,
      },
    });
    if (hasSeoData(seo)) {
      await prisma.seoMetadata.create({ data: { pageId: page.id, ...seo } });
    }
  } catch (error) {
    if (isSlugConflict(error)) {
      return { ok: false, fieldErrors: { slug: PAGES_FORM_LABELS.slugTaken } };
    }
    console.error("createPage failed:", error);
    return { ok: false, message: PAGES_FORM_LABELS.error };
  }

  return { ok: true, slug };
}

export async function updatePage(input: PageInput & { currentSlug: string }): Promise<PageMutationResult> {
  const { currentSlug, ...rawInput } = input;
  const result = normalizePageInput(rawInput);
  if (!result.ok) return { ok: false, fieldErrors: result.fieldErrors };
  const { data, slugAutoGenerated } = result;

  const current = await prisma.page.findUnique({
    where: { slug: currentSlug },
    select: { id: true, status: true, publishedAt: true },
  });
  if (!current) return { ok: false, message: PAGES_FORM_LABELS.error };

  const slug = await resolveUniqueSlug("page", data.slug, slugAutoGenerated, current.id);
  if (slug === null) return { ok: false, fieldErrors: { slug: PAGES_FORM_LABELS.slugTaken } };

  const publishedAt = data.status === "PUBLISHED" ? current.publishedAt ?? new Date() : null;

  try {
    const { seo, ...pageData } = data;
    await prisma.$transaction([
      prisma.page.update({
        where: { id: current.id },
        data: {
          ...pageData,
          slug,
          content: pageData.content === null ? Prisma.DbNull : pageData.content,
          publishedAt,
        },
      }),
      seoWriteOps(current.id, seo),
    ]);
  } catch (error) {
    if (isSlugConflict(error)) {
      return { ok: false, fieldErrors: { slug: PAGES_FORM_LABELS.slugTaken } };
    }
    console.error("updatePage failed:", error);
    return { ok: false, message: PAGES_FORM_LABELS.error };
  }

  return { ok: true, slug };
}

export async function deletePage(slug: string): Promise<{ ok: boolean }> {
  try {
    await prisma.page.delete({ where: { slug } });
  } catch {
    return { ok: false };
  }

  return { ok: true };
}
